def sha256_file(path: Path) -> str:
    return canon.sha256_file(path)


def parse_filename(name: str):
    m = FILENAME_RE.fullmatch(name)
    if not m:
        return None
    return m.group(1).upper(), int(m.group(2)), int(m.group(3))


def analyze_file(path: Path, interval_writer: csv.DictWriter) -> dict:
    parsed = parse_filename(path.name)
    strategy, mode, run = parsed
    target = TARGET_LABEL[mode]
    cond = f"{strategy}{target}"
    key = canon.FileKey(path.name, strategy, mode, target, run)

    result = canon.parse_trace(path, key, interval_writer)
    frames = result["frames"]
    header = result["header"]
    parse_errors = result["parse_errors"]

    ts = np.asarray([f.timestamp_us for f in frames], dtype=np.int64)
    duration_s = (ts[-1] - ts[0]) / 1e6 if len(ts) > 1 else 0.0
    backwards = int(np.sum(np.diff(ts) < 0)) if len(ts) > 1 else 0
    duplicates = int(np.sum(np.diff(ts) == 0)) if len(ts) > 1 else 0

    nominal_bps = float(header["nominal_bit_rate_bps"])
    data_bps = float(header["data_bit_rate_bps"])
    if not (np.isfinite(nominal_bps) and np.isfinite(data_bps)):
        nominal_bps, data_bps = canon.LOOKUP_NOMINAL_BPS, canon.LOOKUP_DATA_BPS

    groups: dict[int, list] = defaultdict(list)
    for fr in frames:
        groups[fr.can_id].append(fr)

    expected_ids = set(canon.EXPECTED[strategy])
    observed = set(groups)
    missing_ids = sorted(expected_ids - observed)
    unexpected_ids = sorted(
        cid for cid in observed
        if cid not in expected_ids and not (0x300 <= cid <= 0x30F)
    )
    dummy_ids = sorted(cid for cid in observed if 0x300 <= cid <= 0x30F)
    dummy_frames = sum(len(groups[c]) for c in dummy_ids)
    control_frames = sum(len(groups[c]) for c in observed if c in expected_ids)

    # per-ID QC + layout + payload byte-identity (reuse expected_kind / EXPECTED_PAYLOAD)
    layout_ok_all = True
    payload_fixed_all = True
    id_rows = []
    total_airtime_us = 0.0
    id_airtime = {}
    esi_total = 0
    fd_total = 0
    brs_total = 0
    for cid, grp in sorted(groups.items()):
        kind, exp_len, period = canon.expected_kind(strategy, cid)
        lengths = sorted(set(f.length for f in grp))
        payload_counter = Counter(f.payload for f in grp)
        is_fd_all = all(f.is_fd for f in grp)
        brs_all = all(f.brs for f in grp)
        esi_count = sum(f.esi for f in grp)
        esi_total += esi_count
        fd_total += sum(f.is_fd for f in grp)
        brs_total += sum(f.brs for f in grp)
        fps = len(grp) / duration_s if duration_s > 0 else np.nan
        exp_payload = canon.EXPECTED_PAYLOAD[strategy].get(cid)
        payload_match = (
            (len(payload_counter) == 1 and next(iter(payload_counter)) == exp_payload)
            if exp_payload is not None else None
        )
        layout_ok = (
            kind != "unexpected" and len(lengths) == 1
            and (exp_len is None or lengths[0] == exp_len)
            and is_fd_all and brs_all and esi_count == 0
        )
        if kind != "unexpected":
            layout_ok_all = layout_ok_all and layout_ok
        if exp_payload is not None and payload_match is False:
            payload_fixed_all = False
        if len(payload_counter) != 1 and kind == "signal":
            payload_fixed_all = False

        # occupancy contribution (ISO-corrected airtime, reused wire_breakdown)
        cid_airtime = 0.0
        for payload, count in payload_counter.items():
            sample = next(f for f in grp if f.payload == payload)
            wb = canon.wire_breakdown(cid, payload, sample.esi, nominal_bps, data_bps, legacy=False)
            cid_airtime += float(wb["estimated_airtime_us"]) * count
        total_airtime_us += cid_airtime
        id_airtime[cid] = cid_airtime

        id_rows.append(dict(
            source_file=path.name, strategy=strategy, target=target, condition=cond,
            can_id_hex=f"0x{cid:03X}", frame_kind=kind, frame_count=len(grp), fps=fps,
            observed_dlc_bytes="|".join(map(str, lengths)),
            expected_dlc_bytes=("" if exp_len is None else exp_len),
            unique_payload_count=len(payload_counter),
            within_run_byte_identical=(len(payload_counter) == 1),
            matches_defined_payload=payload_match,
            is_fd_all=is_fd_all, brs_all=brs_all, esi_count=esi_count,
            occupancy_contribution_pct=(cid_airtime / (duration_s * 1e6) * 100 if duration_s > 0 else np.nan),
        ))

    reconstructed_occupancy_pct = (
        total_airtime_us / (duration_s * 1e6) * 100 if duration_s > 0 else np.nan
    )
    background_fps = dummy_frames / duration_s if duration_s > 0 else np.nan
    control_fps = control_frames / duration_s if duration_s > 0 else np.nan

    # 0x100 inter-arrival metrics (reused interval_metrics), full window
    ts100 = np.asarray([f.timestamp_us for f in frames if f.can_id == 0x100], dtype=np.int64)
    metrics, gaps, errors = canon.interval_metrics(ts100, duration_s, warmup_us=0)

    # error-frame heuristic (parser flags via type token; reuse frame attrs)
    error_frame_count = sum(1 for f in frames if "ERR" in f.type_token.upper())

    # ---- naming-vs-content mapping QC ---------------------------------------
    exp_0x100_dlc = canon.EXPECTED[strategy][0x100][0]  # A=8 B=32 C=64
    obs_0x100_dlc = sorted(set(f.length for f in groups.get(0x100, [])))
    letter_ok = (obs_0x100_dlc == [exp_0x100_dlc])
    if mode == 0:
        number_dummy_ok = (dummy_frames == 0)
    else:
        number_dummy_ok = (dummy_frames > 0)

    qc_flags = {
        "parse_ok": len(parse_errors) == 0 and len(frames) > 0,
        "monotonic_ok": backwards == 0,
        "all_standard_id": all(f.can_id <= 0x7FF for f in frames),
        "fd_all": fd_total == len(frames),
        "brs_all": brs_total == len(frames),
        "no_esi": esi_total == 0,
        "no_error_frames": error_frame_count == 0,
        "layout_ok": layout_ok_all,
        "no_missing_expected_id": len(missing_ids) == 0,
        "no_unexpected_id": len(unexpected_ids) == 0,
        "payload_byte_identical": payload_fixed_all,
        "letter_mapping_ok": letter_ok,          # 0x100 DLC matches A8/B32/C64
        "number_dummy_mapping_ok": number_dummy_ok,  # baseline OFF vs dummy present
    }
    qc_pass = all(qc_flags.values())

    qc_row = dict(
        source_file=path.name, file_size_bytes=path.stat().st_size, sha256=sha256_file(path),
        strategy=strategy, mode=mode, target=target, condition=cond, run=run,
        dummy_gap_us=DUMMY_GAP_US.get((strategy, mode), ""),
        trc_version=header["trc_version"], start_time_text=header["start_time_text"],
        nominal_bit_rate_bps=nominal_bps, data_bit_rate_bps=data_bps,
        duration_s=duration_s, total_frames=len(frames), parse_error_count=len(parse_errors),
        timestamp_backwards_count=backwards, timestamp_duplicate_count=duplicates,
        observed_id_count=len(groups),
        observed_ids="|".join(f"0x{c:03X}" for c in sorted(groups)),
        missing_expected_ids="|".join(f"0x{c:03X}" for c in missing_ids),
        unexpected_ids="|".join(f"0x{c:03X}" for c in unexpected_ids),
        dummy_id_count=len(dummy_ids), dummy_frame_count=dummy_frames,
        control_frame_count=control_frames,
        obs_0x100_dlc_bytes="|".join(map(str, obs_0x100_dlc)),
        expected_0x100_dlc_bytes=exp_0x100_dlc,
        frame_0x100_count=int(len(ts100)),
        fd_frame_count=fd_total, brs_frame_count=brs_total, esi_frame_count=esi_total,
        error_frame_count=error_frame_count,
        gap_gt_6000_count=metrics["gap_gt_6000_count"],
        near_10ms_frame_loss_candidate_count=metrics["near_10ms_frame_loss_candidate_count"],
        reconstructed_occupancy_pct=reconstructed_occupancy_pct,
        background_fps=background_fps,
        **{f"qc_{k}": v for k, v in qc_flags.items()},
        qc_pass=qc_pass,
    )

    summary_row = dict(
        source_file=path.name, strategy=strategy, target=target, condition=cond, run=run,
        dummy_gap_us=DUMMY_GAP_US.get((strategy, mode), ""),
        duration_s=duration_s,
        actual_pcan_mean_load="",  # not saved this campaign
        reconstructed_occupancy_pct=reconstructed_occupancy_pct,
        total_frames=len(frames), control_frames=control_frames,
        background_frames=dummy_frames, background_fps=background_fps, control_fps=control_fps,
        frame_0x100_count=int(len(ts100)),
        n_intervals=metrics["number_intervals"],
        mean_interval_us=metrics["mean_gap_us"],
        median_interval_us=metrics["median_gap_us"],
        jitter_std_us=metrics["jitter_std_us"],
        min_interval_us=metrics["min_gap_us"],
        max_interval_us=metrics["max_gap_us"],
        abs_error_mean_us=metrics["abs_error_mean_us"],
        abs_error_median_us=metrics["abs_error_median_us"],
        abs_error_p95_us=metrics["abs_error_p95_us"],
        abs_error_p99_us=metrics["abs_error_p99_us"],
        abs_error_max_us=metrics["abs_error_max_us"],
        gt100us_count=metrics["abs_error_gt_100us_count"],
        gt100us_rate_pct=(metrics["abs_error_gt_100us_rate"] * 100
                          if np.isfinite(metrics["abs_error_gt_100us_rate"]) else np.nan),
        gap_gt_6000_count=metrics["gap_gt_6000_count"],
        near_10ms_candidate_count=metrics["near_10ms_frame_loss_candidate_count"],
    )

    # ---- section E: predecessor-class exploratory ---------------------------
    pred_rows = []
    idx100 = [i for i, f in enumerate(frames) if f.can_id == 0x100]
    for j in range(1, len(idx100)):
        cur = idx100[j]
        gap = frames[cur].timestamp_us - frames[idx100[j - 1]].timestamp_us
        err = gap - NOMINAL_PERIOD_US
        prev = frames[cur - 1] if cur > 0 else None
        if prev is None:
            pclass = "none"
        else:
            k = canon.expected_kind(strategy, prev.can_id)[0]
            pclass = {"dummy": "background", "signal": "other_control",
                      "unexpected": "other"}.get(k, "other")
        pred_rows.append(dict(
            condition=cond, strategy=strategy, target=target,
            predecessor_class=pclass,
            predecessor_id_hex=(f"0x{prev.can_id:03X}" if prev else ""),
            error_us=float(err), abs_error_us=abs(float(err)),
        ))

    errors_full = errors  # for ECDF
    return dict(qc_row=qc_row, summary_row=summary_row, id_rows=id_rows,
                pred_rows=pred_rows, errors=errors_full, condition=cond,
                strategy=strategy, mode=mode, target=target,
                ts100=ts100, gaps=gaps)


def main() -> int:
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    trc_files = sorted(RAW_DIR.glob("*.trc"), key=lambda p: p.name.lower())
    assert trc_files, f"no TRC files under {RAW_DIR}"

    interval_path = OUT_DIR / "interarrival_samples.csv"
    interval_cols = ["source_file", "strategy", "load_mode", "load_pct_label", "run",
                     "analysis_window", "timestamp_us", "gap_us", "error_us", "abs_error_us"]

    qc_rows, summary_rows, id_rows, pred_rows = [], [], [], []
    per_cond = {}

    with interval_path.open("w", newline="", encoding="utf-8-sig") as fh:
        iw = csv.DictWriter(fh, fieldnames=interval_cols)
        iw.writeheader()
        for p in trc_files:
            if parse_filename(p.name) is None:
                qc_rows.append(dict(source_file=p.name, qc_pass=False,
                                    qc_filename_mismatch=True))
                continue
            print(f"[parse] {p.name}")
            r = analyze_file(p, iw)
            qc_rows.append(r["qc_row"])
            summary_rows.append(r["summary_row"])
            id_rows.extend(r["id_rows"])
            pred_rows.extend(r["pred_rows"])
            per_cond[r["condition"]] = r

    qc_df = pd.DataFrame(qc_rows)
    summary_df = pd.DataFrame(summary_rows)
    id_df = pd.DataFrame(id_rows)
    pred_df = pd.DataFrame(pred_rows)

    # cross-condition naming-mapping monotonicity check (per strategy)
    mono_notes = []
    for s in STRATEGIES:
        sub = summary_df[summary_df.strategy == s].set_index("target")
        occ = [sub.loc[t, "reconstructed_occupancy_pct"] for t in ("baseline", "30", "60", "80") if t in sub.index]
        mono = all(x < y for x, y in zip(occ, occ[1:]))
        mono_notes.append(f"{s}: occupancy baseline<30<60<80 monotonic = {mono} ({', '.join(f'{v:.2f}' for v in occ)})")

    # predecessor-class aggregate (section E, descriptive only)
    pred_summary = []
    if not pred_df.empty:
        for (cond, pclass), g in pred_df.groupby(["condition", "predecessor_class"]):
            ae = g["abs_error_us"].to_numpy(float)
            pred_summary.append(dict(
                condition=cond, predecessor_class=pclass, n=len(g),
                share_of_intervals_pct=np.nan,  # filled below
                mean_abs_error_us=float(ae.mean()),
                median_abs_error_us=float(np.median(ae)),
                p95_abs_error_us=float(np.percentile(ae, 95)),
                gt100us_rate_pct=float(np.mean(ae > 100) * 100),
            ))
    pred_sum_df = pd.DataFrame(pred_summary)
    if not pred_sum_df.empty:
        totals = pred_df.groupby("condition").size()
        pred_sum_df["share_of_intervals_pct"] = pred_sum_df.apply(
            lambda r: r["n"] / totals[r["condition"]] * 100, axis=1)

    # --- write CSV deliverables ----------------------------------------------
    def wcsv(df, name):
        df.to_csv(OUT_DIR / name, index=False, encoding="utf-8-sig", lineterminator="\n")

    wcsv(qc_df, "qc_by_file.csv")
    wcsv(summary_df, "summary_by_condition.csv")
    wcsv(id_df, "summary_by_id.csv")
    wcsv(pred_sum_df, "predecessor_class_summary.csv")

    # run_manifest.csv
    manifest_rows = []
    for _, r in summary_df.sort_values(["strategy", "target"]).iterrows():
        manifest_rows.append(dict(
            filename=r["source_file"], strategy=r["strategy"], target=r["target"], run=r["run"],
            dummy_gap_us=r["dummy_gap_us"], duration_s=round(r["duration_s"], 3),
            actual_pcan_mean_load="",  # not recorded this campaign
            reconstructed_occupancy_pct=round(r["reconstructed_occupancy_pct"], 4),
            background_fps=round(r["background_fps"], 2) if np.isfinite(r["background_fps"]) else "",
            notes="n=1 pilot; PCAN Listen-Only; external background TX node; "
                  "occupancy is reconstructed (not PCAN actual Mean Load)",
        ))
    pd.DataFrame(manifest_rows).to_csv(OUT_DIR / "run_manifest.csv", index=False,
                                       encoding="utf-8-sig", lineterminator="\n")

    # input hashes
    pd.DataFrame([dict(source_file=r["source_file"], file_size_bytes=r["file_size_bytes"],
                       sha256=r["sha256"]) for r in qc_rows if "sha256" in r]).to_csv(
        OUT_DIR / "input_file_sha256.csv", index=False, encoding="utf-8-sig", lineterminator="\n")

    # environment
    (OUT_DIR / "environment_info.txt").write_text(
        "\n".join([
            f"generated_at_local={datetime.now().astimezone().isoformat()}",
            f"platform={platform.platform()}",
            f"python_version={platform.python_version()}",
            f"numpy=={np.__version__}", f"pandas=={pd.__version__}",
            f"reused_module={CANON_DIR / 'analyze_fixed2_64b_n10.py'}",
            f"reused_module_sha256={sha256_file(CANON_DIR / 'analyze_fixed2_64b_n10.py')}",
            "design=3x4x1 (n=1 per condition); no bootstrap; no significance test",
        ]) + "\n", encoding="utf-8")

    # --- figures --------------------------------------------------------------
    make_figures(summary_df, per_cond)

    # --- markdown report ------------------------------------------------------
    write_report(qc_df, summary_df, id_df, pred_sum_df, mono_notes)

    print("QC pass:", int(qc_df.get("qc_pass", pd.Series(dtype=bool)).sum()), "/", len(qc_df))
    return 0


def order_conditions(summary_df):
    order = []
    for t in ("baseline", "30", "60", "80"):
        for s in STRATEGIES:
            c = f"{s}{t}"
            if (summary_df.condition == c).any():
                order.append(c)
    return order


def make_figures(summary_df, per_cond):
    sdf = summary_df.set_index("condition")

    # 1) 12-condition jitter
    order = order_conditions(summary_df)
    fig, ax = plt.subplots(figsize=(9, 4.5))
    vals = [sdf.loc[c, "jitter_std_us"] for c in order]
    colors = [COLORS[c[0]] for c in order]
    ax.bar(order, vals, color=colors)
    ax.set_ylabel("0x100 inter-arrival jitter SD (us)")
    ax.set_title("3-node pilot (n=1): 0x100 inter-arrival jitter, 12 conditions")
    ax.tick_params(axis="x", rotation=45)
    ax.grid(axis="y", alpha=.25)
    _save(fig, "01_jitter_12conditions")

    # 2) per-target grouped A/B/C jitter
    fig, ax = plt.subplots(figsize=(8, 4.5))
    targets = ["baseline", "30", "60", "80"]
    x = np.arange(len(targets)); w = 0.26
    for i, s in enumerate(STRATEGIES):
        yv = [sdf.loc[f"{s}{t}", "jitter_std_us"] if f"{s}{t}" in sdf.index else np.nan for t in targets]
        ax.bar(x + (i - 1) * w, yv, w, label=s, color=COLORS[s])
    ax.set_xticks(x); ax.set_xticklabels(targets)
    ax.set_xlabel("Target condition"); ax.set_ylabel("Jitter SD (us)")
    ax.set_title("3-node pilot (n=1): jitter by target, A/B/C")
    ax.legend(title="Strategy", frameon=False); ax.grid(axis="y", alpha=.25)
    _save(fig, "02_jitter_by_target_ABC")

    # 3) A2/B2/C2 60-target focus: jitter, p99, >100 rate, occupancy
    fig, axes = plt.subplots(1, 4, figsize=(13, 4))
    conds60 = [c for c in ("A60", "B60", "C60") if c in sdf.index]
    metrics = [("jitter_std_us", "Jitter SD (us)"),
               ("abs_error_p99_us", "|error| p99 (us)"),
               ("gt100us_rate_pct", ">100us rate (%)"),
               ("reconstructed_occupancy_pct", "Reconstructed occupancy (%)")]
    for ax, (m, lbl) in zip(axes, metrics):
        ax.bar(conds60, [sdf.loc[c, m] for c in conds60], color=[COLORS[c[0]] for c in conds60])
        ax.set_title(lbl, fontsize=10); ax.grid(axis="y", alpha=.25)
    fig.suptitle("3-node pilot (n=1): 60-target A/B/C load-matched comparison")
    _save(fig, "03_60target_A2B2C2")

    # 4) inter-arrival error ECDF (60-target + baselines)
    fig, ax = plt.subplots(figsize=(8, 4.5))
    for c in ("A60", "B60", "C60", "A0", "C0"):
        if c in per_cond:
            v = np.sort(per_cond[c]["errors"])
            if len(v):
                ax.step(v, np.arange(1, len(v) + 1) / len(v), where="post",
                        color=COLORS[c[0]], linestyle=("-" if c.endswith("60") else "--"), label=c)
    ax.set_xlim(-250, 250); ax.set_xlabel("0x100 inter-arrival error (us)"); ax.set_ylabel("ECDF")
