"""3-node external-background CAN-FD pilot analysis (run1, n=1 per condition).

This driver DOES NOT redefine any timing/occupancy metric.  It imports the
verified n=10 analysis module (``analyze_fixed2_64b_n10.py``) and reuses its
exact definitions:

- ``parse_trace``            -> frame parsing + header + parse-error capture
- ``interval_metrics``       -> 0x100 inter-arrival jitter / abs-error / tail
- ``wire_breakdown``         -> ISO-corrected per-frame airtime (occupancy)
- ``expected_kind``          -> signal / dummy / unexpected classification
- ``EXPECTED`` / ``EXPECTED_PAYLOAD`` -> per-strategy frame layout + fixed payload

The 3-node dataset differs from the 2-node campaign only in:
- filenames are ``a0_1.trc`` .. ``c3_1.trc`` (no ``_fixed2`` suffix, run==1),
- background traffic (0x300-0x30F) is generated by a SEPARATE background TX node,
- there is exactly ONE run per condition (n=1) -> NO bootstrap / NO cross-run
  statistics / NO significance testing is performed.

Original TRC files are never modified.  Everything is written under this
output directory.
"""
